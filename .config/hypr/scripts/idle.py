#!/usr/bin/env python3
"""idle.py - what happens when the laptop is left alone, with separate times on battery and
plugged in (Settings -> Power -> When idle).

    idle.py start              write ~/.config/hypr/hypridle.conf from your times, (re)start hypridle
                               (not while Caffeine is on)
    idle.py do <ac|battery> <dim|lock|sleep>   run by hypridle: acts only on that power source
    idle.py undo <dim|lock>    run by hypridle when you come back

Times live in ~/.config/hypr/idle.json, in minutes (0 = never):
    {"battery": {"dim": 10, "lock": 15, "sleep": 20}, "ac": {"dim": 10, "lock": 15, "sleep": 20}}
hypridle.conf is generated: change the times in Settings, not in that file.
"""

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HOME = Path.home()
HYPR = HOME / ".config" / "hypr"
CONFIG = HYPR / "idle.json"
OUT = HYPR / "hypridle.conf"
SCRIPTS = Path(__file__).resolve().parent
CAFFEINE = HOME / ".cache" / "caffeine_active"
DIMMED = Path(os.environ.get("XDG_RUNTIME_DIR", "/tmp")) / "idle-dimmed"
ACTIONS = ("dim", "lock", "sleep")
DEFAULTS = {"battery": {"dim": 10, "lock": 15, "sleep": 20}, "ac": {"dim": 10, "lock": 15, "sleep": 20}}


def read_times():
    times = json.loads(json.dumps(DEFAULTS))
    try:
        saved = json.loads(CONFIG.read_text(encoding="utf-8"))
        for src in times:
            for a in ACTIONS:
                v = saved.get(src, {}).get(a)
                if isinstance(v, (int, float)) and v >= 0:
                    times[src][a] = int(v)
    except (OSError, ValueError, AttributeError):
        pass
    return times


def save_times(times):
    CONFIG.write_text(json.dumps(times, indent=2) + "\n", encoding="utf-8")


def power_source():
    """'ac' or 'battery'. A computer without a battery counts as plugged in."""
    base = Path("/sys/class/power_supply")
    try:
        for ps in base.iterdir():
            if (ps / "type").read_text().strip() == "Mains":
                return "ac" if (ps / "online").read_text().strip() == "1" else "battery"
        for ps in base.glob("BAT*"):
            return "battery" if (ps / "status").read_text().strip() == "Discharging" else "ac"
    except OSError:
        pass
    return "ac"


def generate():
    times = read_times()
    me = f"python3 {SCRIPTS / 'idle.py'}"
    lines = [
        "# Generated by ~/.config/hypr/scripts/idle.py from idle.json: change the times in",
        "# Settings -> Power -> When idle (edits here are overwritten).",
        "general {",
        "    lock_cmd = pidof hyprlock || hyprlock",
        "    before_sleep_cmd = pidof hyprlock || hyprlock    # lock before sleep/hibernate",
        "    after_sleep_cmd = hyprctl dispatch dpms on",
        "    inhibit_sleep = 1                               # wait for hyprlock before sleep",
        "}",
    ]
    for src in ("battery", "ac"):
        for a in ACTIONS:
            minutes = times[src][a]
            if minutes <= 0:
                continue
            lines += ["", "listener {",
                      f"    timeout = {minutes * 60}    # {src}: {a} after {minutes} min",
                      f"    on-timeout = {me} do {src} {a}"]
            if a != "sleep":
                lines.append(f"    on-resume = {me} undo {a}")
            lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def start():
    generate()
    subprocess.run(["pkill", "-x", "hypridle"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if CAFFEINE.exists() or not shutil.which("hypridle"):
        return
    subprocess.Popen(["hypridle"], stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                     stderr=subprocess.DEVNULL, start_new_session=True)


def act(src, action):
    if power_source() != src:
        return
    if action == "dim":
        subprocess.run(["brightnessctl", "-s", "set", "10"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        DIMMED.touch()
    elif action == "lock":
        subprocess.run(["bash", str(SCRIPTS / "idle-lock-screen.sh")])
    elif action == "sleep":
        subprocess.run(["systemctl", "suspend"])


def undo(action):
    if action == "dim" and DIMMED.exists():
        DIMMED.unlink(missing_ok=True)
        subprocess.run(["brightnessctl", "-r"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    elif action == "lock":
        subprocess.run(["hyprctl", "dispatch", "dpms", "on"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def main():
    args = sys.argv[1:]
    if args[:1] == ["start"]:
        start()
    elif args[:1] == ["do"] and len(args) == 3 and args[1] in DEFAULTS and args[2] in ACTIONS:
        act(args[1], args[2])
    elif args[:1] == ["undo"] and len(args) == 2:
        undo(args[1])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
